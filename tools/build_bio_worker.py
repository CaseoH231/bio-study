"""Packs the app into one Cloudflare Worker script (files stored inside the code) and writes a wrangler config next to it.
Only needed for deploying without GitHub. Usage: python3 tools/build_bio_worker.py OUT_DIR   then:  npx wrangler deploy -c OUT_DIR/wrangler.jsonc"""
import base64, json, mimetypes, os, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
out = sys.argv[1]
name = sys.argv[2] if len(sys.argv) > 2 else 'bio-study'  # e.g. bio-study-preview for a trial copy
skip = {'wrangler.jsonc', '.assetsignore', '_headers', 'README.md', 'CLAUDE.md', '.gitignore', 'package.json', 'package-lock.json'}
types = {'.js': 'text/javascript', '.css': 'text/css', '.html': 'text/html; charset=utf-8', '.svg': 'image/svg+xml',
         '.png': 'image/png', '.webmanifest': 'application/manifest+json', '.json': 'application/json'}
files = {}
for d, dirs, names in os.walk(root):
    dirs[:] = [x for x in dirs if not x.startswith('.') and x not in ('tests', 'tools', 'node_modules', 'worker', 'published')]
    for n in names:
        if n in skip or n.startswith('.'):
            continue
        p = os.path.join(d, n)
        rel = '/' + os.path.relpath(p, root).replace(os.sep, '/')
        ext = os.path.splitext(n)[1]
        files[rel] = [types.get(ext) or mimetypes.guess_type(n)[0] or 'application/octet-stream', base64.b64encode(open(p, 'rb').read()).decode()]
files['/'] = files['/index.html']

worker = """// Generated by tools/build_bio_worker.py – serves Bio Study Notes. Don't edit by hand.
import { handleApi } from %s;
const FILES = %s;
const bytes = (b64) => Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
export default {
  fetch(request, env) {
    const path = new URL(request.url).pathname;
    if (path.startsWith('/api/')) return handleApi(request, env);
    const f = FILES[path] || FILES[path.replace(/\\/$/, '') + '/index.html'];
    if (!f) return new Response('Not found', { status: 404 });
    return new Response(bytes(f[1]), { headers: { 'content-type': f[0], 'cache-control': 'no-cache' } });
  },
};
""" % (json.dumps(os.path.abspath(os.path.join(root, "worker", "api.js"))), json.dumps(files))
os.makedirs(out, exist_ok=True)
open(os.path.join(out, 'worker.js'), 'w').write(worker)
open(os.path.join(out, 'wrangler.jsonc'), 'w').write(json.dumps({'name': name, 'main': 'worker.js', 'compatibility_date': '2026-10-01', 'compatibility_flags': ['nodejs_compat'], 'ai': {'binding': 'AI'}, 'workers_dev': True}, indent=2))
print(len(files) - 1, 'files packed,', len(worker) // 1024, 'KB')
